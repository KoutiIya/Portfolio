"""Package only tracked website files for Cloudflare Workers Static Assets."""
from pathlib import Path
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'dist'
MARKER = '.portfolio-generated'
tracked = subprocess.check_output(
    ['git', 'ls-files', '-z', '--', 'Portfolio/'], cwd=ROOT
).decode().split('\0')
files = [Path(name) for name in tracked if name]
if not files or not any(path == Path('Portfolio/index.html') for path in files):
    raise SystemExit('The tracked portfolio index was not found.')
if OUTPUT.exists() and (OUTPUT.is_symlink() or not (OUTPUT / MARKER).is_file()):
    raise SystemExit('Refusing to replace an unrecognised dist directory.')

with tempfile.TemporaryDirectory(prefix='portfolio-package-') as scratch:
    prepared = Path(scratch) / 'assets'
    prepared.mkdir()
    for relative in files:
        source = ROOT / relative
        if source.is_symlink() or not source.is_file():
            raise SystemExit(f'Expected a regular tracked file: {relative}')
        if source.suffix.lower() in {'.py', '.blend', '.heic', '.db', '.sqlite', '.sqlite3'}:
            raise SystemExit(f'Unexpected non-website file: {relative}')
        destination = prepared / relative.relative_to('Portfolio')
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, destination)
    (prepared / MARKER).write_text('Generated by scripts/prepare_deploy.py\n')
    (prepared / '.assetsignore').write_text(f'{MARKER}\nREADME.md\n')
    if OUTPUT.exists():
        shutil.rmtree(OUTPUT)
    shutil.copytree(prepared, OUTPUT)
print(f'Prepared {len(files)} tracked website files in dist; untracked and ignored files excluded.')
